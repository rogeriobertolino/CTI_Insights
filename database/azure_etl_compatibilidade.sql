-- Migracao especifica do Azure legado; executar com scripts/azure-database.py.
-- Compatibiliza a estrutura anterior do Azure sem apagar tabelas ou registros.
-- As tabelas plurais permanecem intactas. Novas tabelas usam o contrato atual.
ALTER TABLE consultor ALTER COLUMN senha DROP NOT NULL;
ALTER TABLE cliente ALTER COLUMN email DROP NOT NULL;
ALTER TABLE cliente ADD COLUMN IF NOT EXISTS codigo_cti VARCHAR(80);
ALTER TABLE cliente ADD COLUMN IF NOT EXISTS cidade VARCHAR(120);
ALTER TABLE cliente ADD COLUMN IF NOT EXISTS uf VARCHAR(2);
ALTER TABLE cliente ADD COLUMN IF NOT EXISTS lote_id BIGINT;

DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM cliente WHERE codigo_cti IS NULL) THEN
        RAISE EXCEPTION 'Clientes antigos sem codigo CTI: mapeie os codigos reais antes de migrar.';
    END IF;
END $$;
ALTER TABLE cliente ALTER COLUMN codigo_cti SET NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uk_cliente_codigo_cti_etl ON cliente(codigo_cti);

-- IDs legados sao identity no Azure; nenhum ID existente e alterado.
DO $$ DECLARE t text; c text; seq text; BEGIN
    FOR t,c IN SELECT * FROM (VALUES ('cliente','id_cliente'),('consultor','id_consultor')) AS x(t,c) LOOP
        IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name=t AND column_name=c AND (is_identity='YES' OR column_default IS NOT NULL)) THEN
            EXECUTE format('ALTER TABLE %I ALTER COLUMN %I ADD GENERATED BY DEFAULT AS IDENTITY',t,c);
            seq := pg_get_serial_sequence(t,c);
            EXECUTE format('SELECT setval(%L, GREATEST(COALESCE(MAX(%I),0)+1,1), false) FROM %I',seq,c,t);
        END IF;
    END LOOP;
END $$;

CREATE TABLE IF NOT EXISTS servico (
    id_servico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL, descricao TEXT, categoria VARCHAR(100), preco NUMERIC(15,2)
);
CREATE TABLE IF NOT EXISTS contrato (
    id_contrato BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL REFERENCES cliente(id_cliente),
    id_servico BIGINT NOT NULL REFERENCES servico(id_servico),
    data_inicio DATE NOT NULL, data_fim DATE, valor NUMERIC(15,2),
    status VARCHAR(10) NOT NULL CHECK(status IN ('ATIVO','PENDENTE','ENCERRADO','CANCELADO')),
    lote_id BIGINT
);
-- Havendo dados no modelo anterior, nao se inventam datas ou valores para copia-los.
DO $$ BEGIN
    IF EXISTS(SELECT 1 FROM contratos) OR EXISTS(SELECT 1 FROM servicos) THEN
        RAISE EXCEPTION 'Ha servicos/contratos legados: preparar mapeamento antes de criar o modelo novo.';
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS upload_lote (
    id BIGSERIAL PRIMARY KEY, arquivo_nome VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK(status IN ('PENDENTE','PROCESSANDO','PROCESSADO','ERRO')),
    total_linhas INTEGER NOT NULL, linhas_validas INTEGER NOT NULL, linhas_invalidas INTEGER NOT NULL,
    linhas_com_aviso INTEGER NOT NULL, linhas_rejeitadas_etl INTEGER NOT NULL DEFAULT 0,
    mensagem VARCHAR(500), enviado_por VARCHAR(254),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, processado_em TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS segmento(id BIGSERIAL PRIMARY KEY,nome VARCHAR(100) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS estatistica_lote (
    id BIGSERIAL PRIMARY KEY, lote_id BIGINT NOT NULL UNIQUE REFERENCES upload_lote(id),
    resultado TEXT NOT NULL, criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,email VARCHAR(254) NOT NULL UNIQUE,senha_hash VARCHAR(100) NOT NULL,
    perfil VARCHAR(20) NOT NULL DEFAULT 'USER',status_cadastro VARCHAR(20) NOT NULL DEFAULT 'APROVADO',
    cadastrado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,revisado_em TIMESTAMPTZ,revisado_por VARCHAR(254),
    matricula VARCHAR(30),turma VARCHAR(60),reset_password_token_hash VARCHAR(64),
    reset_password_expires_at TIMESTAMPTZ,reset_password_requested_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_cliente_consultor ON cliente(id_consultor);
CREATE INDEX IF NOT EXISTS idx_cliente_segmento ON cliente(segmento);
CREATE INDEX IF NOT EXISTS idx_cliente_nivel ON cliente(nivel);
CREATE INDEX IF NOT EXISTS idx_cliente_lote ON cliente(lote_id);
CREATE INDEX IF NOT EXISTS idx_contrato_cliente ON contrato(id_cliente);
CREATE INDEX IF NOT EXISTS idx_contrato_servico ON contrato(id_servico);
