-- CTI Insights — tabelas do PostgreSQL (local, Neon ou Azure).
-- Pode rodar mais de uma vez: tudo usa IF NOT EXISTS.
-- Quem grava: usuarios -> Java (Spring Boot); upload_lote -> Java cria, Python atualiza;
-- segmento, consultor, servico, cliente, contrato, estatistica_lote -> Python (banco.py).
-- As telas de gestão comercial do Spring também leem/escrevem cliente, consultor, servico e contrato.

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    senha_hash VARCHAR(100) NOT NULL,                      -- BCrypt, nunca a senha
    perfil VARCHAR(20) NOT NULL DEFAULT 'USER' CHECK (perfil IN ('USER', 'ADMIN')),
    status_cadastro VARCHAR(20) NOT NULL DEFAULT 'APROVADO'
        CHECK (status_cadastro IN ('PENDENTE', 'APROVADO', 'RECUSADO', 'BLOQUEADO')),
    cadastrado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revisado_em TIMESTAMP WITH TIME ZONE,
    revisado_por VARCHAR(254),
    matricula VARCHAR(30),
    turma VARCHAR(60),
    reset_password_token_hash VARCHAR(64),
    reset_password_expires_at TIMESTAMP WITH TIME ZONE,
    reset_password_requested_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS upload_lote (
    id BIGSERIAL PRIMARY KEY,
    arquivo_nome VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('PENDENTE', 'PROCESSANDO', 'PROCESSADO', 'ERRO')),
    total_linhas INTEGER NOT NULL,                         -- linhas da planilha (boas + ruins)
    linhas_validas INTEGER NOT NULL,
    linhas_invalidas INTEGER NOT NULL,                     -- barradas no Vue ou no Spring
    linhas_com_aviso INTEGER NOT NULL,
    linhas_rejeitadas_etl INTEGER NOT NULL DEFAULT 0,      -- recusadas na limpeza do Python
    mensagem VARCHAR(500),                                 -- motivo quando status = ERRO
    enviado_por VARCHAR(254),
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processado_em TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS segmento (
    id BIGSERIAL PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE                      -- Indústria, Comércio... sem repetir
);

CREATE TABLE IF NOT EXISTS consultor (
    id_consultor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,                    -- gerado: anasouza@cti.local
    telefone VARCHAR(30),
    matricula VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS servico (
    id_servico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    descricao TEXT,
    categoria VARCHAR(100),
    preco NUMERIC(15, 2)
);

CREATE TABLE IF NOT EXISTS cliente (
    id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_cti VARCHAR(80) NOT NULL UNIQUE,
    id_consultor BIGINT NOT NULL REFERENCES consultor (id_consultor),
    nome_empresa VARCHAR(180) NOT NULL,
    segmento VARCHAR(100) NOT NULL,
    faturamento_anual NUMERIC(15, 2) NOT NULL,
    nivel CHAR(1) NOT NULL CHECK (nivel IN ('A', 'B', 'C')),
    status VARCHAR(10) NOT NULL CHECK (status IN ('ATIVO', 'INATIVO')),
    email VARCHAR(254),
    cidade VARCHAR(120),
    uf VARCHAR(2),
    lote_id BIGINT                                         -- último lote que trouxe o cliente
);

CREATE TABLE IF NOT EXISTS contrato (
    id_contrato BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL REFERENCES cliente (id_cliente),
    id_servico BIGINT NOT NULL REFERENCES servico (id_servico),
    data_inicio DATE NOT NULL,
    data_fim DATE,
    valor NUMERIC(15, 2),
    status VARCHAR(10) NOT NULL CHECK (status IN ('ATIVO', 'PENDENTE', 'ENCERRADO', 'CANCELADO')),
    lote_id BIGINT                                         -- uma linha por serviço contratado
);

CREATE TABLE IF NOT EXISTS estatistica_lote (
    id BIGSERIAL PRIMARY KEY,
    lote_id BIGINT NOT NULL UNIQUE REFERENCES upload_lote (id),
    resultado TEXT NOT NULL,                               -- JSON do dashboard (analise.py)
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_cliente_consultor ON cliente (id_consultor);
CREATE INDEX IF NOT EXISTS idx_cliente_segmento ON cliente (segmento);
CREATE INDEX IF NOT EXISTS idx_cliente_nivel ON cliente (nivel);
CREATE INDEX IF NOT EXISTS idx_cliente_lote ON cliente (lote_id);
CREATE INDEX IF NOT EXISTS idx_contrato_cliente ON contrato (id_cliente);
CREATE INDEX IF NOT EXISTS idx_contrato_servico ON contrato (id_servico);

